                <p class="style1"><strong>&nbsp;</strong></p>
                <p class="style1"><strong>Introduction</strong></p>
                <p align="justify" class="style1"><br />
                  To ensure safety of women  in universities and colleges, the&nbsp;University Grants Commission&nbsp;has set up a  task force to review security arrangements at higher educational institutions  across the country. The  task force will  identify shortcomings in the existing system, analyse and assess them, and  suggest measures to put in place 'strong safeguards' for safety of both female  students and employees.&nbsp;<br />
                  In the wake of increasing crime against women and persuant  to the Directives of the Honourable Supreme Court of India, the Management and  Administration of the RKDF University   have decided to constitute a Women’s Grievance  Cell to uphold the dignity of women at work.<br />
                  In the Indian Constitution, Right to  Equality is a Fundamental Right that includes the right to equality before law,  prohibition of discrimination and equality of opportunities in matters of  public employment. The Supreme Court of India in its August 13, 1997 judgment  in Vishakha &amp;others vs. State of Rajasthan &amp; others makes it obligatory  for every employer and other responsible persons to follow the guidelines laid  down by the Court and to evolve a specific policy to combat sexual harassment  in the workplace. Educational institutions are bound by the same directive.<br />
                  <br />
                  In compliance with the mandate of the  Supreme Court judgment, RKDF University has adopted this policy to prevent,  prohibit and punish sexual harassment of women at the workplace. University is  committed to provide for all female employees   who fall within its jurisdiction including its academic, non - academic  staff and  students, a place of work and  study free frfrom sexual harassment, intimidation and exploitation. Every woman  shall have a Right to be free from Sexual Harassment and the Right to Work in  an environment free from any form of Sexual harassment.</p>
                <p align="justify" class="style1">&nbsp;</p>
                <p align="justify" class="style1"><strong>Objectives of the Cell</strong><br />
                  The Cell seeks to inform the campus  community of their right to a respectful work and learning environment. It  believes that if we practice respect, exercise empathy in our interactions with  others so that we do not hurt anyone through what we say or do then we can  create a campus that is free of sexual harassment. Simple respect for all on  the campus community is thus the focus. </p>
                <p align="justify" class="style1">&nbsp;</p>
                <p align="justify" class="style1"><strong>Functions of the Cell</strong><br />
                  To promote  gender equality and create an enabling environment for gender justice where men  and women can work together with a sense of personal security and dignity<strong>.</strong> <br />
                  To facilitate a gender-sensitive and  congenial working environment at RKDF University so that women at work place  are not subjected to gender specific discrimination or sexual harassment. <br />
                  To suggest  academic measures and action programmes to bring about changes in practices and  attitudes within society towards recognising the fundamental right to gender  equality.&nbsp;<br />
                  <br />
                  To find possible ways on how gender education and sensitisation can be made an  integral part of the university curriculum in all subject domains. <br />
                  To provide empathetic counselling  environment for psychological empowerment to students and local women about  their problems which they cannot share easily.<br />
                  <br />
                  To analyze underlying causes through research to women discrimination and to  generate awareness.<br />
                  <br />
                  To sensitise the women students of University and society about their  individual growth like nutrition, health, hygiene and sanitation.</p>
                <p align="justify" class="style1">To facilitate the economic  empowerment of women by meeting with various self help groups, NGO's and other  government organisations.<br />
    To recommend punitive action against the guilty to the  Honorable Vice Chancellor.</p>
                <p align="justify" class="style1"><br />
</p>
                <p align="justify" class="style1"><strong>The Cell  seeks to achieve these goals through:</strong></p>
                <p align="justify" class="style1"><br />
                  <strong>Dissemination  of Information</strong>&nbsp;– Through production, distribution and  circulation of printed materials, posters and handouts<br />
                  <br />
                  <strong>Awareness Workshops</strong>&nbsp;– About sexual harassment for faculty,  non-teaching staff and students. The aim is to develop nonthreatening and  non-intimidating atmosphere of mutual learning.<br />
                  <br />
                  <strong>Counselling</strong>&nbsp;– Confidential counselling service is an important  service as it provides a safe space to speak about the incident and how it has  affected the victim because sexual harassment cases are rarely reported and is  a sensitive issue.&nbsp; <br />
                  <strong>Guest/Extension Lectures- </strong>The lectures of eminent personalities from NGOs,  civil authorities, academicians and experts working in the area.</p>
                <p align="justify" class="style1"><strong>&nbsp;</strong></p>
                <p align="justify" class="style1"><strong>The  Complaint Mechanism<br />
                  Procedure to file/report a complaint:</strong> </p>
                <p align="justify" class="style1">&nbsp;</p>
                <div align="justify" class="style1">
                  <ul type="square">
                    <li>The complainant will have to       submit a written and signed complaint addressed to the Secretary of the       Cell.</li>
                    <li>The counsellor will call the       complainant for a personal meeting, usually within a week from the       submission of the written complaint.</li>
                    <li>The members of the Cell will discuss the complaint.</li>
                    <li>If the case falls outside the purview of the Cell, the complainant will be informed about the same by       the appropriate authority.</li>
                    <li>If the case comes under the purview of the Cell, an enquiry committee will be set up. The Committee       will submit a report and recommend the nature of action to be taken at the earliest by specifying the appropriate authorities.</li>
                  </ul>
