NCC ‘B’ certificate सीनियर डिविजन या विंग के छात्रों को दिया &nbsp;&nbsp;&nbsp;&nbsp;&nbsp;जाता है। इसके लिए दो साल SW/ SD के रूप में पूरा करना होता है।<br />
