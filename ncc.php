                                <p align="justify"><span class="style6">MOTTO OF NCC</span><br /><br />
The need for having motto for the Corps was discussed in the 11th Central Advisory Committee (CAC) meeting held on 11 Aug 1978. The mottos suggested were "Duty and Discipline"; "Duty, Unity and Discipline"; "Duty and Unity"; "Unity and Discipline". The final decision for selection of "Unity and Discipline" as motto for the NCC was taken in the 12th CAC meeting held on 12 Oct 1980.</p>
<p>&nbsp;</p><p>&nbsp;</p><p>&nbsp;</p>
                                <p align="justify"><span class="style6">PLEDGE OF NCC</span><br /><br />
WE THE CADET OF THE NATIONAL CADET CORPS,
DO SOLEMNLY PLEDGE THAT WE SHALL ALWAYS UPHOLD THE UNITY OF INDIA.
WE RESOLVE TO BE DISCIPLINED AND RESPONSIBLE CITIZEN OF OUR NATION.
WE SHALL UNDERTAKE POSITIVE COMMUNITY SERVICE IN THE SPIRIT OF SELFLESSNESS
AND CONCERN FOR OUR FELLOW BEINGS.</p>

