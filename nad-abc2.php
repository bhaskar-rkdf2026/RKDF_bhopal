                 <p>&nbsp; <strong>ABOUT NAD – DIGILOCKER & ACADEMIC BANK OF CREDITS (ABC):</strong></p>
            <p >&nbsp;NAD Digilocker is an initiative of Ministry of Electronics and Information Technology (MeitY) and Ministry of Human Resources Development (MHRD). MHRD has appointed UGC as nodal agency for implementation of NAD scheme through DigiLocker. NAD-DigiLocker aims to provide paperless government, facilitated the students to get authentic Educational documents/certificate in digital format which was issued by their Academic institutions. The NAD ecosystem comprises of the Academic Institutions, Students, Verifying Partners, and NAD Repository.</p>
